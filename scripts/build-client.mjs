#!/usr/bin/env node
/**
 * Build client.js — the single browser module of this bundle.
 *
 * A DSH bundle owns exactly one client module (id = package name), so the three
 * former client halves (Confluence panel, pro-prompt input controls, Crisp
 * status page) are composed here: each source file's factory is captured, its
 * plugin object is created, and one plugin that applies all three is registered
 * under the bundle's package name.
 *
 * Sources live in client-sources/ and are the members' own client files.
 * Crisp's page is not composed: the quality gate is off by default and the host
 * side is only applied when config.crisp.enabled is true, so a always-registered
 * status page would be dead UI. Re-add ./client-sources/crisp.js here if the
 * gate is turned on permanently.
 *
 * Run after changing any client source:
 *   node scripts/build-client.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const here = dirname(fileURLToPath(import.meta.url))
const root = dirname(here)
const packageName = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).name

const SOURCES = [
  'client-sources/confluence.js',
  'client-sources/pro-prompt.js',
  'client-sources/restart-row.js',
  'client-sources/hub-assist.js',
]

/** Capture the factory function text from a module-loader client file. */
function factoryText(file) {
  const captured = []
  const window = { __ModuleLoader__: { load(definition) { captured.push(definition) } } }
  // The files only touch `window` at top level; factories run later.
  new Function('window', readFileSync(join(root, file), 'utf8'))(window)
  if (captured.length !== 1) throw new Error(`expected exactly one module registration in ${file}, got ${captured.length}`)
  const { id, factory } = captured[0]
  if (typeof factory !== 'function') throw new Error(`no factory in ${file} (id ${id})`)
  const text = factory.toString()
  return /^\s*(async\s+)?factory\s*\(/.test(text) ? `({${text}}).factory` : `(${text})`
}

const parts = SOURCES.map(factoryText)
const out = [
  '/*!',
  ' * dsh-assist-suite — merged browser module (generated by scripts/build-client.mjs).',
  ' * Composes: assistant hub page (the single sidebar entry), Confluence panel,',
  ' * pro-prompt composer controls.',
  ' */',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(packageName)},`,
  '  factory: require => {',
  '    const pageSources = []',
  '    const parts = []',
  '    const add = (part) => { if (part === null || part === undefined) return; parts.push(part); if (Array.isArray(part.pages)) pageSources.push(part.pages) }',
  ...parts.map((text, index) => `    add(${text}(require, pageSources)) // source ${index + 1}`),
  '    const inject = []',
  '    for (const part of parts) for (const name of part.inject ?? []) if (!inject.includes(name)) inject.push(name)',
  '    return {',
  '      inject,',
  '      apply(ctx) { for (const part of parts) part.apply(ctx) },',
  '    }',
  '  },',
  '})',
  '',
].join('\n')

const outFile = join(root, 'client.js')
writeFileSync(outFile, out, 'utf8')
execFileSync(process.execPath, ['--check', outFile], { stdio: 'pipe' })
process.stdout.write(`wrote client.js (${out.length} bytes, ${parts.length} surfaces)\n`)
